"""Stage demo: one sentence -> pack -> conformance 5/5 -> activate, against core.

  set -a; source .env; set +a
  python -m compiler.demo_pack "A team memory assistant that forgets notes after 30 days"
  python -m compiler.demo_pack --cached "..."     skip the LLM, serve the closest cached pack

Uses only contract routes: POST /packs, POST /packs/{id}/conformance, POST /packs/{id}/activate
(CORE_API_URL, default :8001). Activation is core's call: it refuses anything below 5/5.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

from compiler.directive import DirectiveError
from compiler.pack import compile_pack, record_conformance


def _post(http, base, path, body=None):
    r = http.post(base + path, json=body or {})
    try:
        data = r.json()
    except ValueError:
        data = {}
    return r.status_code, data


def run(sentence: str, core: str, cached: bool = False, client=None) -> int:
    import httpx

    if cached:
        os.environ["PACK_LLM_MAX_CALLS"] = "0"
    try:
        res = compile_pack(sentence)
    except DirectiveError as e:
        print(f"[1/4] compile failed: {e.detail}")
        return 1
    pack = res["pack"]
    tag = {"llm": "generated by the LLM", "cache": "served from cache", "fallback": "LLM unavailable, closest cached pack"}[res["source"]]
    if cached and res["source"] == "fallback":
        tag, res["reason"] = "closest cached pack, LLM skipped (--cached)", None
    print(f"[1/4] pack {pack['pack_id']} ({tag})" + (f" | {res['reason']}" if res.get("reason") else ""))
    print(f"      scope: {pack['scope_field']} | nodes: {', '.join(pack['node_types'])} | "
          f"gate: {'; '.join(g['field'] + ' ' + g['op'] + ' ' + str(g['value_from_scope'] or g['value']) for g in pack['gate'])} | "
          f"decay: {pack['decay']['kind']} {pack['decay']['seconds']}s")

    base = core.rstrip("/")
    http = client or httpx.Client(timeout=120)
    try:
        st, body = _post(http, base, "/packs", {"pack": pack})
        if st >= 400:
            detail = (body.get("error") or {}).get("detail", "")
            if "is active" in detail:
                print(f"[2/4] {pack['pack_id']} is already active on core (packs are immutable once active)")
                return 0
            print(f"[2/4] register failed: HTTP {st} {detail}")
            return 1
        print(f"[2/4] registered on core as {body.get('status', 'draft')}")

        st, conf = _post(http, base, f"/packs/{pack['pack_id']}/conformance")
        if st >= 400:
            print(f"[3/4] conformance failed to run: HTTP {st} {(conf.get('error') or {}).get('detail', '')}")
            return 1
        print(f"[3/4] conformance {conf.get('passed')}/{conf.get('total')}")
        for c in conf.get("checks", []):
            print(f"      {'PASS' if c.get('passed') else 'FAIL'}  {c.get('name')}" + (f"  ({c['detail']})" if c.get("detail") and not c.get("passed") else ""))
        record_conformance(pack["pack_id"], conf)

        st, act = _post(http, base, f"/packs/{pack['pack_id']}/activate")
        if st >= 400:
            print(f"[4/4] not activated: {(act.get('error') or {}).get('code')} ({(act.get('error') or {}).get('detail', '')})")
            return 1
        print(f"[4/4] {act.get('pack_id')} is {act.get('status')}")
        return 0
    except httpx.HTTPError as e:
        print(f"core unreachable at {base}: {type(e).__name__}")
        return 1
    finally:
        if client is None:
            http.close()


def main() -> int:
    ap = argparse.ArgumentParser(description="sentence -> pack -> conformance -> activate")
    ap.add_argument("sentence")
    ap.add_argument("--core", default=os.getenv("CORE_API_URL", "http://localhost:8001"))
    ap.add_argument("--cached", action="store_true", help="no LLM call; serve the closest cached pack")
    a = ap.parse_args()
    return run(a.sentence, a.core, a.cached)


if __name__ == "__main__":
    sys.exit(main())
